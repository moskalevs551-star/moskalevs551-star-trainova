export type SampleQuizKey = keyof typeof SAMPLE_LIBRARY;

export function getSampleQuizzes() {
  return Object.entries(SAMPLE_LIBRARY).map(([key, sample]) => ({
    key: key as SampleQuizKey,
    title: sample.title,
    fileName: sample.fileName,
  }));
}

export function createSampleQuiz(key: SampleQuizKey) {
  const sample = SAMPLE_LIBRARY[key];
  const quiz = parseQstText(sample.text, {
    title: sample.title,
    fileName: sample.fileName,
    format: "qst",
    encoding: "utf-8",
  });

  return { ...quiz, isDemo: true };
}
